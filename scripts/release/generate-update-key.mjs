import { generateKeyPairSync } from "node:crypto";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const root = resolve(scriptDir, "..", "..");
const privatePath = resolve(root, "packaging", ".update-signing-private.pem");
const publicPath = resolve(root, "src", "update_public_key.py");
const force = process.argv.includes("--force");
if (existsSync(privatePath) && !force) {
  throw new Error(`Refusing to replace the existing update key: ${privatePath}`);
}

const { privateKey, publicKey } = generateKeyPairSync("rsa", {
  modulusLength: 3072,
  publicExponent: 0x10001,
});
const pem = privateKey.export({ type: "pkcs8", format: "pem" });
const jwk = publicKey.export({ format: "jwk" });
const modulus = BigInt(`0x${Buffer.from(jwk.n, "base64url").toString("hex")}`);
mkdirSync(dirname(privatePath), { recursive: true });
writeFileSync(privatePath, pem, { encoding: "utf8", mode: 0o600 });
writeFileSync(
  publicPath,
  `"""Public half of the dedicated production update-signing key.\n\nGenerated by scripts/release/generate-update-key.mjs. The private half is never\ncommitted or bundled with the application.\n"""\n\nUPDATE_PUBLIC_KEY_N: int | None = int(\n    "${modulus.toString()}"\n)\nUPDATE_PUBLIC_KEY_E = 65537\n`,
  "utf8",
);
process.stdout.write(`${privatePath}\n${publicPath}\n`);
